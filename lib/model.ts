// The token radar's model, version 2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// pre-token protocols below the watchlist floor with the most TVL: the early rows the radar exists to
// find. A protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id,
// no symbol); live-token protocols are kept apart and shown at the market's own values, never mixed in.
//
// Implied value follows only from the snapshot's own figures:
//
//   base        = tvl_usd x BASE_MULTIPLE        (a launch read off locked capital)
//   growthMult  = 1 + (clamped change_7d / 100) x GROWTH_WEIGHT
//   maturity    = MATURITY_FLOOR + min(age_days, MATURITY_DAYS) / MATURITY_DAYS x MATURITY_RANGE
//   chainMult   = 1 + CHAIN_WEIGHT x min(chains - 1, CHAIN_CAP)
//   sectorMult  = the category's multiplier, the SECTOR table (a sector's launches price its capital)
//   implied     = max(1, round(base x growthMult x maturity x chainMult x sectorMult))
//
// Every factor comes from the snapshot's own record. No protocol name is ever special-cased: the same
// function scores every row, and the dashboard's model sandbox lets a reader re-run it live.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

