/** The category's multiplier: the first SECTOR row the category name matches, else 1.0. */
export function sectorOf(category: string | null): { mult: number; why: string } {
  const c = (category ?? '').toLowerCase();
  for (const [match, mult, why] of SECTOR) if (c.includes(match)) return { mult, why };
  return { mult: 1.0, why: 'a general protocol: the base multiple stands' };
}

